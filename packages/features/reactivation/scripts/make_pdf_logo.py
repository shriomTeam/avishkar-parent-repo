"""Writes web/lib/pdf-logo.ts from a PNG: the logo printed at the top of every page of the summary report.

    uv run python scripts/make_pdf_logo.py path/to/logo.png

The PNG must be RGB, 8 bits per channel, not interlaced and without transparency, so a PDF can hold its data as it
is. Use an image at least 600 pixels wide; the report prints it about 0.5 inch tall.
"""

import base64
import struct
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "web" / "lib" / "pdf-logo.ts"


def main(path: str) -> None:
    data = Path(path).read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit("not a PNG file")
    width, height, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", data[16:29])
    if (depth, color, interlace) != (8, 2, 0):
        sys.exit(
            f"the PNG must be RGB, 8-bit, no transparency, not interlaced (this one is depth {depth}, type {color}, interlace {interlace})"  # noqa: E501
        )
    OUT.write_text(
        "// Generated by scripts/make_pdf_logo.py. To change the logo, run that script on the new PNG.\n"
        f"// Source: {Path(path).name}, {width} x {height} pixels.\n"
        f'export const REPORT_LOGO_PNG_BASE64 =\n  "{base64.b64encode(data).decode()}";\n'
    )
    print(f"wrote {OUT} ({width} x {height})")


if __name__ == "__main__":
    main(sys.argv[1])
