"""Writes web/lib/pdf-widths.ts: the character widths of Helvetica and Helvetica-Bold in the WinAnsi encoding.

The summary report's PDF writer sets text in the standard Helvetica fonts, which every PDF reader has, so it needs the
widths to wrap lines. They come from the Adobe core-font metrics (.afm files). Run once; the output is committed:

    uv run python scripts/make_pdf_widths.py /usr/share/matplotlib/mpl-data/fonts/pdfcorefonts
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "web" / "lib" / "pdf-widths.ts"

SYMBOLS = {
    160: "space", 161: "exclamdown", 162: "cent", 163: "sterling", 164: "currency", 165: "yen", 166: "brokenbar",
    167: "section", 168: "dieresis", 169: "copyright", 170: "ordfeminine", 171: "guillemotleft", 172: "logicalnot",
    173: "hyphen", 174: "registered", 175: "macron", 176: "degree", 177: "plusminus", 178: "twosuperior",
    179: "threesuperior", 180: "acute", 181: "mu", 182: "paragraph", 183: "periodcentered", 184: "cedilla",
    185: "onesuperior", 186: "ordmasculine", 187: "guillemotright", 188: "onequarter", 189: "onehalf",
    190: "threequarters", 191: "questiondown", 215: "multiply", 247: "divide", 198: "AE", 208: "Eth", 222: "Thorn",
    223: "germandbls", 216: "Oslash", 230: "ae", 240: "eth", 254: "thorn", 248: "oslash",
    128: "Euro", 130: "quotesinglbase", 131: "florin", 132: "quotedblbase", 133: "ellipsis", 134: "dagger",
    135: "daggerdbl", 136: "circumflex", 137: "perthousand", 138: "Scaron", 139: "guilsinglleft", 140: "OE",
    142: "Zcaron", 145: "quoteleft", 146: "quoteright", 147: "quotedblleft", 148: "quotedblright", 149: "bullet",
    150: "endash", 151: "emdash", 152: "tilde", 153: "trademark", 154: "scaron", 155: "guilsinglright", 156: "oe",
    158: "zcaron", 159: "Ydieresis", 39: "quotesingle", 96: "grave",
}  # fmt: skip


def main(folder: str) -> None:
    out = ["// Generated by scripts/make_pdf_widths.py from the Adobe core-font metrics. Do not edit by hand.",
           "// Widths in 1/1000 em for codes 32 to 255 of the WinAnsi (Windows-1252) encoding; 0 means no glyph.", ""]  # fmt: skip  # noqa: E501
    for font, const in (("Helvetica", "HELVETICA_WIDTHS"), ("Helvetica-Bold", "HELVETICA_BOLD_WIDTHS")):
        by_code: dict[int, int] = {}
        by_name: dict[str, int] = {}
        for line in (Path(folder) / f"{font}.afm").read_text().splitlines():
            if line.startswith("C "):
                parts = {p.split()[0]: p.split()[1] for p in line.split(";") if p.strip()}
                width, name = int(parts["WX"]), parts["N"]
                by_name[name] = width
                if int(parts["C"]) >= 0:
                    by_code[int(parts["C"])] = width
        widths = []
        for code in range(32, 256):
            if code in SYMBOLS:
                w = by_name.get(SYMBOLS[code], 0)
            elif code < 127:
                w = by_code.get(code, 0)
            else:
                ch = bytes([code]).decode("cp1252", errors="ignore")
                base = unicodedata.normalize("NFD", ch)[:1] if ch else ""
                w = by_name.get(base, 0) if base.isalpha() and base.isascii() else 0
            widths.append(w)
        out.append(f"export const {const}: readonly number[] = [")
        for i in range(0, len(widths), 16):
            out.append("  " + ", ".join(str(w) for w in widths[i : i + 16]) + ",")
        out += ["];", ""]
    specials = {c: bytes([c]).decode("cp1252") for c in range(128, 160) if c not in (129, 141, 143, 144, 157)}
    out.append("/** Unicode code points above U+00FF that WinAnsi has, and the byte each one is. */")
    out.append("export const WIN_ANSI_EXTRA: Readonly<Record<number, number>> = {")
    out += [f"  {ord(ch)}: {code}," for code, ch in specials.items() if ord(ch) > 255]
    out += ["};", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
